"""
Data contracts, enums, and Pydantic schemas for the Veyra AI Security Engine.

Defines standardized data models for untrusted prompt analysis, deterministic rule findings,
model inferences, and policy evaluation decisions.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class Decision(str, Enum):
    """
    Security decision for an analyzed prompt or document.
    - ALLOW: Low risk, no significant attack patterns detected. Safe to forward to downstream agent.
    - BLOCK: Definite or severe injection/jailbreak attempt. Dropped immediately.
    - QUARANTINE: Borderline, indirect, suspicious, or unverified input requiring human review or sandbox isolation.
    """
    ALLOW = "ALLOW"
    BLOCK = "BLOCK"
    QUARANTINE = "QUARANTINE"


class AttackCategory(str, Enum):
    """
    Taxonomy of prompt injection and adversarial threat categories.
    """
    INSTRUCTION_OVERRIDE = "instruction_override"
    JAILBREAK = "jailbreak"
    SECRET_EXTRACTION = "secret_extraction"
    TOOL_ABUSE = "tool_abuse"
    INDIRECT_INJECTION = "indirect_injection"
    BENIGN = "benign"
    UNCERTAIN = "uncertain"


class RuleSeverity(str, Enum):
    """
    Severity rating for deterministic security rule triggers.
    """
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class AnalysisStatus(str, Enum):
    """
    Execution status of the multi-stage analysis pipeline.
    """
    SUCCESS = "success"
    FALLBACK_RULES_ONLY = "fallback_rules_only"
    MODEL_ERROR = "model_error"
    TIMEOUT = "timeout"
    DEMO_MODE = "demo_mode"


class InferenceMode(str, Enum):
    """
    Source of AI model evaluation.
    - REAL: Generated by live open-weight model API (e.g. Ollama endpoint).
    - DEMO: Generated by explicitly configured offline mock simulation.
    - NONE: No model inference was executed (e.g. pipeline failure or fast-path).
    """
    REAL = "real"
    DEMO = "demo"
    NONE = "none"


class RuleFinding(BaseModel):
    """
    Structured finding produced by deterministic rule engine.
    """
    rule_id: str = Field(description="Unique rule identifier (e.g. RULE-OVERRIDE-001)")
    name: str = Field(description="Human-readable rule name")
    category: AttackCategory = Field(description="Threat category associated with this rule")
    severity: RuleSeverity = Field(description="Severity impact of the matched rule")
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description="Confidence heuristic (0.0 to 1.0) for this pattern match. Note: not a calibrated probability."
    )
    matched_pattern: str = Field(description="Snippet or regex pattern that triggered the rule")
    description: str = Field(description="Explanation of why this rule triggered and security implications")


class RuleAnalysisResult(BaseModel):
    """
    Aggregated findings and score from deterministic rule evaluation.
    """
    has_triggers: bool = Field(default=False, description="Whether any rule matched")
    highest_severity: Optional[RuleSeverity] = Field(default=None, description="Maximum severity among matched rules")
    risk_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Aggregated risk score (0.0=clean to 1.0=critical danger) derived from rule severities."
    )
    findings: List[RuleFinding] = Field(default_factory=list, description="List of matched rule findings")


class AIModelAnalysis(BaseModel):
    """
    Raw structured response parsed from the open-weight LLM.
    
    Score scales:
        - risk_score: 0.0 (completely benign) to 1.0 (severe malicious attack).
        - confidence: 0.0 (low heuristic confidence) to 1.0 (high certainty).
          DOCUMENTATION NOTE: This represents the model's self-assessed subjective certainty,
          NOT an empirical Bayesian or Platt-calibrated probability distribution.
    """
    category: AttackCategory = Field(description="Assigned attack classification")
    risk_score: float = Field(ge=0.0, le=1.0, description="Estimated malicious risk severity (0.0 - 1.0)")
    confidence: float = Field(ge=0.0, le=1.0, description="Subjective certainty score (0.0 - 1.0)")
    explanation: str = Field(description="Detailed natural-language justification for the classification")
    evidence: List[str] = Field(default_factory=list, description="Substrings or indicators demonstrating injection")
    recommended_action: Decision = Field(description="Recommended action according to model analysis")
    raw_response: Optional[str] = Field(default=None, description="Raw model text payload if available")

    @field_validator("category", mode="before")
    @classmethod
    def normalize_category(cls, v: Any) -> Any:
        if isinstance(v, str):
            v_clean = v.strip().lower().replace("-", "_").replace(" ", "_")
            valid_keys = {item.value: item for item in AttackCategory}
            if v_clean in valid_keys:
                return valid_keys[v_clean]
        return v

    @field_validator("recommended_action", mode="before")
    @classmethod
    def normalize_decision(cls, v: Any) -> Any:
        if isinstance(v, str):
            v_clean = v.strip().upper()
            if v_clean in Decision.__members__:
                return Decision[v_clean]
        return v


class PromptAnalysisRequest(BaseModel):
    """
    Incoming request schema for analyzing untrusted prompt or document.
    """
    prompt: str = Field(min_length=1, description="Untrusted prompt or document text to analyze")
    context: Optional[str] = Field(default=None, description="Optional system role or agent context")


class PromptAnalysisResult(BaseModel):
    """
    Final security verdict and structured diagnostics returned by `analyze_prompt`.
    
    Score scales:
        - risk_score (0.0 to 1.0): 
            [0.00, 0.35) = Low risk / Benign
            [0.35, 0.70) = Moderate / Suspicious / Ambiguous (Quarantine band)
            [0.70, 1.00] = High / Critical threat (Block band)
        - confidence (0.0 to 1.0):
            Subjective agreement score synthesized from rule matching and model self-rating.
            Note: Not calibrated probability.
    """
    category: AttackCategory = Field(description="Overall classified attack category")
    risk_score: float = Field(ge=0.0, le=1.0, description="Composite risk score on a 0.0 to 1.0 scale")
    confidence: float = Field(ge=0.0, le=1.0, description="Overall certainty index (0.0 to 1.0)")
    explanation: str = Field(description="Consolidated reasoning explaining the verdict and risks")
    evidence: List[str] = Field(default_factory=list, description="Identified attack signatures or payload fragments")
    recommended_action: Decision = Field(description="Decision recommended by the AI pipeline")
    analysis_status: AnalysisStatus = Field(description="Status of the analysis pipeline")
    inference_mode: InferenceMode = Field(description="Inference provider mode (real, demo, or none)")
    decision: Decision = Field(description="Authoritative policy decision (ALLOW, BLOCK, QUARANTINE)")
    rule_findings: List[RuleFinding] = Field(default_factory=list, description="Findings triggered by deterministic rules")
    pipeline_latency_ms: Optional[float] = Field(default=None, description="Total execution duration in milliseconds")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic telemetry and provider metadata")
